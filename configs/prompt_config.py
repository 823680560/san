def query_classifier_prompt(query: str) -> str:
    """判断查询类型：exact / fuzzy / aggregation"""
    return (
        f"判断问题类型，只输出一个词：exact / fuzzy / aggregation\n\n"
        f"exact = 按地区/金额/日期/状态等条件筛选具体项目记录\n"
        f"fuzzy = 搜索项目名称、公司名、关键词等文本模糊匹配\n"
        f"aggregation = 统计数量、平均值、排名、趋势、分组汇总\n\n"
        f"问题: {query}"
    )


