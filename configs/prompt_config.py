def llm_only_answer_prompt(query: str) -> str:
    """LLM Only 模式：无检索上下文，靠模型自身知识回答"""
    return (
        f"你是一个专业的环卫行业智能问答系统。请回答以下问题。\n\n"
        f"用户问题：{query}\n\n"
        f"请根据你的知识给出准确、详细的回答。如果你不确定，请明确说明。"
    )


def rag_answer_prompt(query: str, context: str) -> str:
    """RAG 模式：基于检索上下文生成回答"""
    return (
        f"你是一个专业的环卫行业智能问答系统。请基于以下提供的参考资料，回答用户的问题。\n\n"
        f"参考资料：\n{context}\n\n"
        f"用户问题：{query}\n\n"
        f"请基于参考资料给出准确、详细的回答。如果参考资料不足以回答问题，请明确说明。"
    )


def ground_truth_answer_prompt(query: str, source_text: str) -> str:
    """生成评测集的参考答案"""
    return (
        f"你是一个专业的环卫行业智能问答系统。请根据以下参考资料，回答用户的问题。\n\n"
        f"要求：\n"
        f"1. 答案必须基于参考资料中的信息，不要编造\n"
        f"2. 答案要全面、准确，尽量覆盖问题涉及的所有知识点\n"
        f'3. 不要输出"根据参考资料"、"根据文本"等前缀，直接给出答案\n\n'
        f"参考资料：\n{source_text}\n\n"
        f"用户问题：{query}\n\n"
        f"答案："
    )


