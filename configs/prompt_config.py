def chunk_relevance_filter_prompt(question: str, chunks_text: str) -> str:
    """判断 context chunk 是否与问题相关（反向过滤）"""
    return (
        f"你是一个数据质量审核专家。请判断以下每个文本片段是否与用户问题相关。\n\n"
        f"判断标准：\n"
        f"- 只要文本片段的部分内容与问题相关，就保留\n"
        f"- 只有完全无关的才剔除\n"
        f"- 宁保留勿剔除（宽松判断）\n\n"
        f"用户问题：{question}\n\n"
        f"文本片段列表：\n{chunks_text}\n\n"
        f"请输出需要保留的片段编号列表（用逗号分隔），例如：0,2,3\n"
        f"如果全部相关，输出：all\n"
        f"如果全部不相关，输出：none\n\n"
        f"只输出编号列表，不要输出其他内容："
    )


def law_question_gen_prompt(truncated_text: str) -> str:
    """为政策法规知识库的文本 chunk 生成自然问题"""
    return (
        f"你是一个环卫行业政策法规知识专家。请根据以下政策法规文本，生成一个用户可能会问的自然问题。\n\n"
        f"要求：\n"
        f"1. 问题必须基于文本中的具体信息\n"
        f'2. 问题必须自然、口语化，像真实用户会问的那样（例如："政府采购法对供应商的资格要求是什么？"）\n'
        f'3. 只输出问题本身，不要输出任何其他内容（不要加"问题："、"问："等前缀）\n'
        f"4. 问题必须是完整的疑问句，以问号结尾\n"
        f"5. 问题要简洁明了\n\n"
        f"文本内容：\n{truncated_text}\n\n"
        f"请直接输出问题："
    )


def project_question_gen_prompt(
    truncated_text: str,
    project_name: str,
    title: str,
    category: str,
    budget: str,
    region: str,
    question_type: str,
) -> str:
    """为项目知识库的文本 chunk 生成自然问题"""
