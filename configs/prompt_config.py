def correctness_eval_prompt(query: str, response: str, reference: str) -> str:
    """评估回答与参考答案的匹配程度（正确性）"""
    return (
        f"你是一个专业的评估助手。请评估以下回答与参考答案的匹配程度。\n\n"
        f"【用户问题】\n{query}\n\n"
        f"【参考答案】\n{reference}\n\n"
        f"【待评估回答】\n{response}\n\n"
        f"请从内容准确性、完整性、一致性三个维度评估待评估回答与参考答案的匹配程度。\n"
        f"只输出一个 0-100 之间的整数分数，不要输出其他内容：\n"
        f"- 0-20: 完全不匹配或严重错误\n"
        f"- 21-40: 部分匹配，但存在明显错误或遗漏\n"
        f"- 41-60: 基本匹配，但有一些差异\n"
        f"- 61-80: 较好匹配，只有细微差异\n"
        f"- 81-100: 高度匹配或完全一致\n\n"
        f"分数："
    )


def relevancy_eval_prompt(query: str, response: str) -> str:
    """评估回答与问题的相关程度"""
    return (
        f"你是一个专业的评估助手。请评估以下回答与用户问题的相关程度。\n\n"
        f"【用户问题】\n{query}\n\n"
        f"【待评估回答】\n{response}\n\n"
        f"请评估回答是否直接回应了问题、是否切题、是否提供了问题所需的信息。\n"
        f"只输出一个 0-100 之间的整数分数，不要输出其他内容：\n"
        f"- 0-20: 完全无关或答非所问\n"
        f"- 21-40: 部分相关，但偏离主题\n"
        f"- 41-60: 基本相关，但不够直接\n"
        f"- 61-80: 较好相关，直接回应了问题\n"
        f"- 81-100: 高度相关，完全切题且信息充分\n\n"
        f"分数："
    )


def faithfulness_eval_prompt(query: str, response: str, context_text: str) -> str:
    """评估回答是否忠实于参考资料（无幻觉）"""
    return (
        f"你是一个专业的评估助手。请评估以下回答是否忠实于提供的参考资料，"
        f"即回答中的信息是否都能在参考资料中找到依据。\n\n"
        f"【用户问题】\n{query}\n\n"
        f"【参考资料】\n{context_text}\n\n"
        f"【待评估回答】\n{response}\n\n"
        f"请检查回答中的每个关键信息点是否都能在参考资料中找到支持。注意：\n"
        f"- 如果回答中的所有信息都能在参考资料中找到依据，则分数高\n"
        f"- 如果回答中存在参考资料中没有的信息（幻觉），则分数低\n"
        f"- 如果回答拒绝回答或说明信息不足，则视为忠实\n\n"
        f"只输出一个 0-100 之间的整数分数，不要输出其他内容：\n"
        f"- 0-20: 严重幻觉，大部分信息无依据\n"
        f"- 21-40: 存在较多无依据信息\n"
        f"- 41-60: 部分信息有依据，部分无依据\n"
        f"- 61-80: 大部分信息有依据，少量无依据\n"
        f"- 81-100: 完全忠实于参考资料\n\n"
        f"分数："
    )


def recall_eval_prompt(query: str, response: str, reference: str) -> str:
    """评估回答对参考答案中关键信息点的覆盖程度"""
    return (
        f"你是一个专业的评估助手。请仅从**信息覆盖完整性**的角度评估以下回答。\n\n"
        f"【用户问题】\n{query}\n\n"
        f"【参考答案（包含全部关键信息点）】\n{reference}\n\n"
        f"【待评估回答】\n{response}\n\n"
        f"评估标准（只关注「有没有遗漏」，不关注「有没有说错」）：\n"
        f"- 先识别参考答案中包含的所有关键信息点（事实、数据、规定、结论等）\n"
        f"- 再检查待评估回答中覆盖了其中多少个关键信息点\n"
        f"- 只要待评估回答提到了某个信息点，就算覆盖（即使表述方式不同）\n"
        f"- 待评估回答中多说的内容不影响评分（不扣分）\n\n"
        f"只输出一个 0-100 之间的整数分数，不要输出其他内容：\n"
        f"- 0-20: 几乎没覆盖，遗漏了绝大部分关键信息\n"
        f"- 21-40: 覆盖了少量关键信息，存在大量遗漏\n"
        f"- 41-60: 覆盖了约一半关键信息\n"
        f"- 61-80: 覆盖了大部分关键信息，少量遗漏\n"
        f"- 81-100: 几乎覆盖了全部关键信息点\n\n"
        f"分数："
    )


def sql_logical_accuracy_prompt(query: str, sql: str, row_count: int) -> str:
    """评估 SQL 查询逻辑是否准确回应了问题"""
    return (
        f"你是一个专业的 NL2SQL 评估助手。请判断以下 SQL 查询的逻辑是否正确回应了用户问题。\n\n"
        f"【用户问题】\n{query}\n\n"
        f"【生成的 SQL】\n{sql}\n\n"
        f"【SQL 返回行数】{row_count}\n\n"
        f"评估标准：\n"
        f"- 检查 SQL 的 WHERE 条件是否准确反映了问题中的筛选条件\n"
        f"- 检查 SELECT 的字段是否包含了回答问题所需的字段\n"
        f"- 列别名（如 COUNT(*) AS 项目数 与 COUNT(*) AS 项目数量）不影响查询语义，不应扣分\n"
        f"- 防御性的数据清洗条件（如 IS NOT NULL）若对核心结果无实质性影响，不应视为错误\n"
        f"- 如果 SQL 执行错误或返回空结果但问题预期有数据，逻辑准确率低\n"
        f"- 如果查询条件完全无关或字段缺失，逻辑准确率低\n\n"
        f"只输出一个 0-100 之间的整数分数，不要输出其他内容：\n"
        f"- 0-20: SQL 完全无关或执行错误，无法回答问题\n"
        f"- 21-40: SQL 部分相关但条件或字段有明显错误\n"
        f"- 41-60: SQL 基本正确但条件不够精确或字段不完整\n"
        f"- 61-80: SQL 较准确，条件与问题匹配，返回了所需字段\n"
        f"- 81-100: SQL 非常准确，条件精确，字段完整，逻辑正确\n\n"
        f"分数："
    )


